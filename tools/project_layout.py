"""本项目目录适配；复用固定 XRobot 的解析、配置检查和生成器。"""

from importlib.metadata import version
from pathlib import Path
import re

import yaml

MODULES = Path("User_File/3_Modules")
USER = Path("User_File/4_Task/User")


def local_records(root):
    """从显式BSP相对路径加载仓内模块；拒绝越界、重复及生成目录。"""
    import xrobot.module_parser as parser

    root = Path(root).resolve()
    local = yaml.safe_load((root / MODULES / "local_modules.yaml").read_text(encoding="utf-8"))
    records = {}
    for entry in local["modules"]:
        identity, relative = entry["id"], entry["path"]
        if not re.fullmatch(r"[A-Za-z0-9_-]+/[A-Za-z][A-Za-z0-9_]*", identity):
            raise ValueError(f"Invalid local module identity: {identity}")
        if not re.fullmatch(r"[A-Za-z0-9_/.-]+", relative):
            raise ValueError(f"Invalid local module path: {relative}")
        folder = (root / relative).resolve()
        if not any(folder.is_relative_to((root / base).resolve())
                   for base in (MODULES, USER.parent)) or folder.is_relative_to(root / USER):
            raise ValueError(f"Local module escaped source directories: {relative}")
        if identity in records:
            raise ValueError(f"Duplicate local module identity: {identity}")
        name = identity.rsplit("/", 1)[1]
        header = folder / (name + ".hpp")
        records[identity] = {"id": identity, "name": name, "path": folder,
                             "header": header,
                             "manifest": parser.parse_manifest_from_header(header)}
    return records


def write_local_cmake(root):
    """生成仓内模块的CMake接入；输入真实BSP根，输出由登记文件派生的清单。"""
    root = Path(root).resolve()
    lines = ["# Generated by tools/xrobot_project.py; do not edit."]
    for record in local_records(root).values():
        relative = record["path"].relative_to(root).as_posix()
        lines.append(f'include("${{CMAKE_CURRENT_SOURCE_DIR}}/{relative}/CMakeLists.txt")')
    (root / MODULES / "local_modules.cmake").write_text(
        "\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def configure_xrobot():
    """仅在当前进程适配目录及仓内模块；不改安装包或外部模块锁。"""
    if version("xrobot") != "1.0.1":
        raise RuntimeError("Project adapter requires xrobot==1.0.1")
    import xrobot.project as layout
    import xrobot.module_parser as parser
    import xrobot.generate_main as generator
    import xrobot.describe as describer
    from xrobot.type_index import TypeIndex

    original_init = layout.Project.__init__
    original_discover = parser.discover_modules
    original_header_lines = layout.Project.header_lines
    original_describe = describer.describe

    def initialize(self, root):
        """设置本项目物理路径；输入仓库根，输出官方Project实例。"""
        original_init(self, root)
        self.modules_dir = self.root / MODULES
        self.modules_yaml = self.modules_dir / "modules.yaml"
        self.sources_yaml = self.modules_dir / "sources.yaml"
        self.user = self.root / USER
        self.header = self.user / "xrobot_main.hpp"
        self.default_config = self.user / "xrobot.yaml"
        self.libxr_config = self.user / "libxr_config.yaml"

    def discover(directory, lock_path):
        """读取已锁外部模块和显式登记的仓内模块；拒绝重名/越界目录。"""
        modules = original_discover(directory, lock_path)
        local = local_records(Path(directory).resolve().parents[1])
        for identity, record in local.items():
            if identity in modules:
                raise ValueError(f"Local module shadows locked dependency: {identity}")
            modules[identity] = record
        for identity in local:
            for request in modules[identity]["manifest"].depends:
                dependency = request.split("@", 1)[0] if isinstance(request, str) else request["id"]
                if dependency not in modules:
                    raise ValueError(f"{identity}: missing declared dependency {dependency}")
        return modules

    def header_lines(self, config, depends, entry):
        """将模块登记/目录适配纳入官方摘要，构建时拒绝未再生成的入口。"""
        extra = [self.modules_dir / "local_modules.yaml", Path(__file__).resolve()]
        return original_header_lines(self, config, depends + extra, entry)

    def describe(project, config=None):
        """官方只读诊断也纳入仓内类型；外部lock记录保持真实且独立。"""
        class LocalTypeIndex:
            @staticmethod
            def for_modules(modules):
                """在官方类型分析前补齐仓内接口，不替换其诊断或验证。"""
                modules.update(local_records(project.root))
                return TypeIndex.for_modules(modules)

        previous_index = describer.TypeIndex
        describer.TypeIndex = LocalTypeIndex
        try:
            result = original_describe(project, config)
        finally:
            describer.TypeIndex = previous_index
        result["local_modules"] = [
            {"id": identity, "path": project.relative(record["path"]),
             "version_source": "BSP"} for identity, record in local_records(project.root).items()
        ]
        return result

    layout.MODULES_YAML = MODULES / "modules.yaml"
    layout.Project.__init__ = initialize
    layout.Project.header_lines = header_lines
    parser.discover_modules = discover
    generator.discover_modules = discover
    describer.describe = describe
